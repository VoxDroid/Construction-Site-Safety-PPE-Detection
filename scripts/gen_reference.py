"""Generate docs/reference/cli.md and docs/reference/configuration.md from the code.

Run it after changing CLI options or settings; CI fails if the committed pages are stale:

    python scripts/gen_reference.py          # write the pages
    python scripts/gen_reference.py --check  # exit 1 if they would change
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

os.environ["COLUMNS"] = "100"  # argparse wraps help to the terminal width; keep the output stable

from pydantic import BaseModel

from ppe_guard.cli import build_parser
from ppe_guard.config import CameraConfig, Settings, Zone

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "reference"
HEADER = "<!-- Generated by scripts/gen_reference.py. Do not edit by hand. -->\n\n"


# ---------------------------------------------------------------------------- CLI


def _subparsers(p: argparse.ArgumentParser):
    for a in p._actions:
        if isinstance(a, argparse._SubParsersAction):
            return a
    return None


def _help(p: argparse.ArgumentParser) -> str:
    return p.format_help().rstrip()


def cli_page() -> str:
    root = build_parser()
    root.prog = "ppe-guard"
    out = [HEADER, "# Command line\n\n",
           "Everything is one command, `ppe-guard`, with subcommands. ",
           "Run `ppe-guard <command> --help` for the same text.\n\n",
           "```text\n", _help(root), "\n```\n"]
    sub = _subparsers(root)
    for name, p in sub.choices.items():
        out.append(f"\n## `{name}`\n\n")
        nested = _subparsers(p)
        out.append("```text\n" + _help(p) + "\n```\n")
        if nested:
            for n2, p2 in nested.choices.items():
                out.append(f"\n### `{name} {n2}`\n\n```text\n{_help(p2)}\n```\n")
    return "".join(out)


# ---------------------------------------------------------------------------- settings


def _type(ann) -> str:
    s = str(ann).replace("typing.", "").replace("ppe_guard.config.", "")
    s = s.replace("<class '", "").replace("'>", "")
    s = s.replace("Literal", "one of ").replace("NoneType", "null")
    return s.replace(" | ", " or ").replace("|", " or ").replace(" or None", " or null")


def _default(field) -> str:
    if field.default_factory is not None:
        v = field.default_factory()
        if isinstance(v, BaseModel):
            return "(section)"
        return "`[]`" if v == [] else f"`{v}`"
    d = field.default
    if field.is_required():
        return "required"
    if d is None:
        return "`null`"
    if isinstance(d, bool):
        return f"`{str(d).lower()}`"
    if isinstance(d, str):
        return f'`"{d}"`'
    return f"`{d}`"


def _limits(field) -> str:
    bits = []
    for m in field.metadata:
        for k, sym in (("ge", "≥"), ("gt", ">"), ("le", "≤"), ("lt", "<"), ("min_length", "min length"),
                       ("max_length", "max length")):
            v = getattr(m, k, None)
            if v is not None:
                bits.append(f"{sym} {v}")
    return ", ".join(bits)


def _table(model: type[BaseModel], prefix: str) -> str:
    rows = ["| Key | Type | Default | Limits | Description |", "| --- | --- | --- | --- | --- |"]
    for name, f in model.model_fields.items():
        desc = (f.description or "").replace("|", "\\|")
        rows.append(f"| `{prefix}{name}` | {_type(f.annotation)} | {_default(f)} | {_limits(f)} | {desc} |")
    return "\n".join(rows) + "\n"


SECTION_TEXT = {
    "general": "Site details.",
    "detection": "How the model runs. `weights` needs a camera restart; the rest apply within a second.",
    "compliance": "What counts as a violation. Applies to every camera; PPE zones can override `required_ppe`.",
    "alerts": "Webhook alerts for new violations.",
    "recording": "Video clips saved with each violation.",
    "storage": "How long data is kept.",
    "analysis": "Limits for the Analyze page.",
}


def config_page() -> str:
    out = [HEADER, "# Configuration\n\n",
           "Settings live in `settings.json` in the data folder (`./data`, or `--data-dir`, or ",
           "`PPE_GUARD_DATA_DIR`). The dashboard's **Settings** page edits the same file, and the ",
           "server validates every change. An invalid file is moved aside to `settings.invalid.json` ",
           "and defaults are used.\n\n",
           "```json\n", Settings().model_dump_json(indent=2), "\n```\n"]
    for name, f in Settings.model_fields.items():
        if name == "cameras":
            continue
        model = f.annotation
        out.append(f"\n## `{name}`\n\n{SECTION_TEXT.get(name, '')}\n\n")
        out.append(_table(model, f"{name}."))
        for sub_name, sf in model.model_fields.items():
            if isinstance(sf.annotation, type) and issubclass(sf.annotation, BaseModel):
                out.append(f"\n`{name}.{sub_name}`:\n\n" + _table(sf.annotation, f"{name}.{sub_name}."))
    out.append("\n## `cameras`\n\nA list of cameras. Add them in **Settings → Cameras** or with the API.\n\n")
    out.append(_table(CameraConfig, "cameras[]."))
    out.append("\n### Zones\n\nEach camera has a list of zones, drawn in the zone editor. "
               "Points are normalised to 0-1 (x to the right, y down).\n\n")
    out.append(_table(Zone, "cameras[].zones[]."))
    out.append("\n## Environment variables\n\n"
               "| Variable | Meaning |\n| --- | --- |\n"
               "| `PPE_GUARD_DATA_DIR` | Data folder (settings, database, snapshots, clips). Default `./data`. |\n"
               "| `PPE_GUARD_MODELS_DIR` | Where model weights are stored and downloaded. Default `./models`. |\n"
               "| `PPE_GUARD_PASSWORD` | Dashboard password. Set at every start, replacing one set in the UI. |\n")
    return "".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    pages = {OUT / "cli.md": cli_page(), OUT / "configuration.md": config_page()}
    stale = []
    for path, text in pages.items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            stale.append(path)
            if not a.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    if a.check and stale:
        print("stale: " + ", ".join(str(p.relative_to(ROOT)) for p in stale)
              + "\nrun: python scripts/gen_reference.py", file=sys.stderr)
        return 1
    print("up to date" if not stale else "wrote " + ", ".join(p.name for p in stale))
    return 0


if __name__ == "__main__":
    sys.exit(main())
